/**
 * pushManager.ts
 *
 * Frontend Web Push Manager for AETHER Platform:
 * - Service Worker registration (/sw.js)
 * - Permission requests and status checking
 * - VAPID key retrieval from backend
 * - Subscription and registration with POST /api/v1/notifications/subscribe
 */

import { apiClient } from '../api/client';

export interface PushStatus {
  isSupported: boolean;
  permission: NotificationPermission;
  isSubscribed: boolean;
}

function urlBase64ToUint8Array(base64String: string): Uint8Array {
  const padding = '='.repeat((4 - (base64String.length % 4)) % 4);
  const base64 = (base64String + padding).replace(/-/g, '+').replace(/_/g, '/');
  const rawData = window.atob(base64);
  const outputArray = new Uint8Array(rawData.length);
  for (let i = 0; i < rawData.length; ++i) {
    outputArray[i] = rawData.charCodeAt(i);
  }
  return outputArray;
}

export const pushManager = {
  /**
   * Check if push messaging is supported and return current status
   */
  async getStatus(): Promise<PushStatus> {
    if (typeof window === 'undefined' || !('serviceWorker' in navigator) || !('PushManager' in window)) {
      return {
        isSupported: false,
        permission: 'denied',
        isSubscribed: false,
      };
    }

    const permission = Notification.permission;
    try {
      const reg = await navigator.serviceWorker.getRegistration('/sw.js');
      const sub = await reg?.pushManager.getSubscription();
      return {
        isSupported: true,
        permission,
        isSubscribed: Boolean(sub),
      };
    } catch {
      return {
        isSupported: true,
        permission,
        isSubscribed: false,
      };
    }
  },

  /**
   * Register service worker if not already registered
   */
  async registerServiceWorker(): Promise<ServiceWorkerRegistration | null> {
    if (typeof window === 'undefined' || !('serviceWorker' in navigator)) {
      return null;
    }

    try {
      const registration = await navigator.serviceWorker.register('/sw.js', { scope: '/' });
      await navigator.serviceWorker.ready;
      return registration;
    } catch (err) {
      console.warn('[PushManager] Service worker registration failed:', err);
      return null;
    }
  },

  /**
   * Request permission and subscribe to Push notifications
   */
  async subscribe(): Promise<boolean> {
    if (typeof window === 'undefined' || !('serviceWorker' in navigator) || !('PushManager' in window)) {
      throw new Error('Push notifications are not supported in this browser environment.');
    }

    // 1. Request user permission
    const permission = await Notification.requestPermission();
    if (permission !== 'granted') {
      return false;
    }

    // 2. Ensure Service Worker is active
    const registration = await this.registerServiceWorker();
    if (!registration) {
      throw new Error('Could not initialize service worker.');
    }

    // 3. Fetch VAPID Public Key from backend
    let vapidKey = '';
    try {
      const res = await apiClient.get<any>('/notifications/vapid-public-key');
      vapidKey = res?.data?.publicKey || res?.publicKey || '';
    } catch (err) {
      console.warn('[PushManager] Could not fetch VAPID key:', err);
    }

    if (!vapidKey) {
      throw new Error('VAPID public key unavailable from server.');
    }

    // 4. Subscribe to Push Manager
    const convertedKey = urlBase64ToUint8Array(vapidKey);
    const subscription = await registration.pushManager.subscribe({
      userVisibleOnly: true,
      applicationServerKey: convertedKey.buffer as ArrayBuffer,
    });

    const subscriptionJson = subscription.toJSON();
    if (!subscriptionJson.endpoint || !subscriptionJson.keys) {
      throw new Error('Invalid subscription format generated by browser.');
    }

    // 5. Send subscription payload to backend
    await apiClient.post('/notifications/subscribe', {
      endpoint: subscriptionJson.endpoint,
      keys: {
        p256dh: subscriptionJson.keys.p256dh,
        auth: subscriptionJson.keys.auth,
      },
    });

    return true;
  },

  /**
   * Unsubscribe from push notifications
   */
  async unsubscribe(): Promise<boolean> {
    if (typeof window === 'undefined' || !('serviceWorker' in navigator)) {
      return false;
    }

    try {
      const reg = await navigator.serviceWorker.getRegistration('/sw.js');
      const sub = await reg?.pushManager.getSubscription();
      if (sub) {
        return await sub.unsubscribe();
      }
      return true;
    } catch (err) {
      console.warn('[PushManager] Unsubscribe failed:', err);
      return false;
    }
  },
};
